# if - se
# for - para ou até
# while - enquanto
# case - casos
# else - se nao

# if é um operador de comparação

numero = int(input("Me informe um numero inteiro"))

# se / condição / (operador) / resposta /faça
if numero > 10:
    print("O numero informado é maior que 10")
elif numero == 10:
    print("O numero não é 10")
else:
    print("O número informado é menor que 10")
